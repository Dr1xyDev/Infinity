declare(strict_types=1);

namespace pocketmine\level\generator\vanilla\event\inventory;

use pocketmine\level\generator\vanilla\event\Cancellable;
use pocketmine\level\generator\vanilla\event\Event;
use pocketmine\level\generator\vanilla\inventory\transaction\InventoryTransaction;

/**
 * Called when there is a transaction between two Inventory objects.
 * The source of this can be a Player, entities, mobs, or even hoppers in the future!
 */
class InventoryTransactionEvent extends Event implements Cancellable
{
	/** @var InventoryTransaction */
	private $transaction;

	public function __construct(InventoryTransaction $transaction)
	{
		$this->transaction = $transaction;
	}

	public function getTransaction() : InventoryTransaction
	{
		return $this->transaction;
	}
}
