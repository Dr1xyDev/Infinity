namespace pocketmine\scheduler;

use pocketmine\plugin\Plugin;

abstract class PluginTask extends Task{

	
	protected $owner;

	
	public function __construct(Plugin $owner){
		$this->owner = $owner;
	}

	
	public final function getOwner(){
		return $this->owner;
	}

}
