abstract class ThreadedLogger extends \pmmp\thread\Thread implements Logger{

    /**
     * Bridges pmmp\thread\Runnable::run() to the onRun() contract used by MainLogger.
     */
    public function run() : void{
        $this->onRun();
    }

    abstract public function onRun() : void;
}
